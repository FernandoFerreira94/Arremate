#!/bin/sh
set -eu
psql --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" --set=ON_ERROR_STOP=1 --set=app_password="$APP_DATABASE_PASSWORD" <<'SQL'
CREATE ROLE auction_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE PASSWORD :'app_password';
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO auction_app;
ALTER DEFAULT PRIVILEGES FOR ROLE auction_owner IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO auction_app;
ALTER DEFAULT PRIVILEGES FOR ROLE auction_owner IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO auction_app;
SQL
